static int fails;

static void check(const char *name, const UCHAR *d, ULONG n, const UCHAR *rep, ULONG rl, int want)
{
    HID_MOUSE_LAYOUT l;
    int r = HidParseMouse(d, n, &l), got;
    if (r != 0) { printf("FAIL %s: not parsed\n", name); fails++; return; }
    if (l.UsesIds) { rep++; rl--; }
    got = Buttons(&l, rep, rl);
    printf("%s %-8s fields %d+%d (first %u, %u) report -> buttons %02x (want %02x), x %ld y %ld\n",
           got == want ? "ok  " : "FAIL", name, l.Buttons.Valid ? l.Buttons.Count : 0,
           l.Buttons2.Valid ? l.Buttons2.Count : 0, l.ButtonsFirst, l.Buttons2First, got, want,
           (long)HidGetField(rep, rl, &l.X, 0), (long)HidGetField(rep, rl, &l.Y, 0));
    if (got != want) fails++;
}

int main(void)
{
    static const UCHAR r1[] = { 0x18, 5, 0xfb, 0 };                  /* buttons 4 + 5 */
    static const UCHAR r1b[] = { 0x09, 5, 0xfb, 0 };                 /* left + 4 */
    static const UCHAR r2[] = { 0x02, 0x08 | 0x02, 0x10, 0x00, 0xf0, 0xff, 0 };   /* 4 + right */
    static const UCHAR r2b[] = { 0x02, 0x10, 0x10, 0x00, 0xf0, 0xff, 0 };         /* 5 */
    static const UCHAR r3[] = { 0x20 | 0x04, 3, 4 };                 /* forward + middle */
    static const UCHAR r3b[] = { 0x10 | 0x08 | 0x01, 3, 4 };         /* back + left (bit 3 is constant) */
    static const UCHAR r4[] = { 0x07, 1, 1 };
    check("one", one, sizeof(one), r1, sizeof(r1), 0x18);
    check("one", one, sizeof(one), r1b, sizeof(r1b), 0x09);
    check("split", split, sizeof(split), r2, sizeof(r2), 0x0A);
    check("split", split, sizeof(split), r2b, sizeof(r2b), 0x10);
    check("usages", usages, sizeof(usages), r3, sizeof(r3), 0x14);
    check("usages", usages, sizeof(usages), r3b, sizeof(r3b), 0x09);
    check("three", three, sizeof(three), r4, sizeof(r4), 0x07);
    printf("RESULT hidparse %s\n", fails ? "FAIL" : "PASS");
    return fails != 0;
}
