void UsbMemSet(void *Dst, int Val, ULONG Len) { memset(Dst, Val, Len); }

/* the mapping of usbhid.c: field bit i is button First + i */
static int Buttons(const HID_MOUSE_LAYOUT *L, const UCHAR *Rep, ULONG Len)
{
    int b = 0, f, i;
    for (f = 0; f < 2; f++) {
        const HID_FIELD *fl = f ? &L->Buttons2 : &L->Buttons;
        int first = f ? L->Buttons2First : L->ButtonsFirst;
        if (!fl->Valid) continue;
        for (i = 0; i < fl->Count && first + i <= 5; i++)
            if (HidGetField(Rep, Len, fl, i)) b |= 1 << (first + i - 1);
    }
    return b;
}

